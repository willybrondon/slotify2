// Language Management
let currentLanguage = localStorage.getItem('skedisy-language') || 'fr';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLanguage = lang;
    localStorage.setItem('skedisy-language', lang);
    document.documentElement.lang = lang;
    translatePage();
    updateLanguageSwitcher();
}

function getTranslation(key) {
    return translations[currentLanguage]?.[key] || translations['fr'][key] || translations['en'][key] || key;
}

function translatePage() {
    // Find all elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        const translation = getTranslation(key);
        
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            element.placeholder = translation;
        } else if (element.hasAttribute('data-translate-html')) {
            element.innerHTML = translation;
        } else {
            element.textContent = translation;
        }
    });
    
    // Update page title
    const titleElement = document.querySelector('title[data-translate]');
    if (titleElement) {
        document.title = getTranslation(titleElement.getAttribute('data-translate'));
    }
}

function updateLanguageSwitcher() {
    const switchers = document.querySelectorAll('.lang-switcher');
    switchers.forEach(switcher => {
        const newLang = currentLanguage === 'fr' ? 'en' : 'fr';
        const newLangName = currentLanguage === 'fr' ? 'English' : 'Français';
        const shortName = currentLanguage === 'fr' ? 'EN' : 'FR';
        
        // Update data-lang attribute
        switcher.setAttribute('data-lang', newLang);
        
        // Update text content - preserve icon if it exists
        const icon = switcher.querySelector('i');
        const span = switcher.querySelector('span');
        
        if (span) {
            // Mobile shows short name, desktop shows full name
            if (switcher.classList.contains('mobile-only')) {
                span.textContent = shortName;
            } else {
                span.textContent = newLangName;
            }
        } else {
            // If no span, update entire content but preserve icon
            if (icon) {
                switcher.innerHTML = icon.outerHTML + ' <span>' + (switcher.classList.contains('mobile-only') ? shortName : newLangName) + '</span>';
            } else {
                switcher.innerHTML = '<i class="fas fa-globe"></i> <span>' + (switcher.classList.contains('mobile-only') ? shortName : newLangName) + '</span>';
            }
        }
    });
}

// Initialize language on page load
function initLanguage() {
    // Get saved language or default to 'fr' (French)
    const savedLang = localStorage.getItem('skedisy-language') || 'fr';
    setLanguage(savedLang);
    
    // Add click handlers to language switchers
    document.querySelectorAll('.lang-switcher').forEach(switcher => {
        // Remove existing listeners to avoid duplicates
        const newSwitcher = switcher.cloneNode(true);
        switcher.parentNode.replaceChild(newSwitcher, switcher);
        
        newSwitcher.addEventListener('click', function(e) {
            e.preventDefault();
            e.stopPropagation();
            const newLang = this.getAttribute('data-lang') || (currentLanguage === 'fr' ? 'en' : 'fr');
            setLanguage(newLang);
        });
    });
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguage);
} else {
    // DOM is already ready
    initLanguage();
}

